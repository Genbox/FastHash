    [Fact]
    public void MatchesUpstreamIndex()
    {
        foreach (UpstreamIndexVector vector in UpstreamIndexVectors)
        {
            Assert.Equal(vector.Expected, Rapid3Hash64.ComputeIndex(vector.Input, vector.Seed));
            Assert.Equal(vector.Expected, Rapid3HashMicro64.ComputeIndex(vector.Input, vector.Seed));
            Assert.Equal(vector.Expected, Rapid3HashNano64.ComputeIndex(vector.Input, vector.Seed));

            if (vector.Seed == 0)
            {
                Assert.Equal(vector.Expected, Rapid3Hash64.ComputeIndex(vector.Input));
                Assert.Equal(vector.Expected, Rapid3HashMicro64.ComputeIndex(vector.Input));
                Assert.Equal(vector.Expected, Rapid3HashNano64.ComputeIndex(vector.Input));
            }
        }
    }

    [Fact]
    public void ComputeIndexMatchesByteHash()
    {
        ulong[] inputs =
        [
            0UL,
            1UL,
            0x0123456789abcdefUL,
            12808224424451380151UL,
            ulong.MaxValue
        ];

        Span<byte> data = stackalloc byte[8];

        foreach (ulong input in inputs)
        {
            BinaryPrimitives.WriteUInt64LittleEndian(data, input);

            Assert.Equal(Rapid3Hash64.ComputeHash(data), Rapid3Hash64.ComputeIndex(input));
            Assert.Equal(Rapid3Hash64.ComputeHash(data, 123), Rapid3Hash64.ComputeIndex(input, 123));
        }
    }

