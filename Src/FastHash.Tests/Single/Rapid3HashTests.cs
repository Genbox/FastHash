    [Fact]
    public void MicroAndNanoRespectSeedOnLongInput()
    {
        ulong micro0 = Rapid3HashMicro64.ComputeHash(Zeros1000);
        ulong micro1 = Rapid3HashMicro64.ComputeHash(Zeros1000, 123);
        ulong nano0 = Rapid3HashNano64.ComputeHash(Zeros1000);
        ulong nano1 = Rapid3HashNano64.ComputeHash(Zeros1000, 123);

        Assert.NotEqual(micro0, micro1);
        Assert.NotEqual(nano0, nano1);
    }

    private static byte[] CreateData(int length)
    {
        byte[] data = new byte[length];

        for (int i = 0; i < data.Length; i++)
            data[i] = unchecked((byte)((i * 7) + 3));

        return data;
    }

